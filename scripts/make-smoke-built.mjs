// Deterministic generator for tests/smoke-built.ts — the "run the smoke
// suite against the BUILT lib/ instead of src/" variant that previously only
// existed inside scripts/compatibility/Run-Checks.ps1 (its runtime text
// rewrite). The output is gitignored; run before the built smoke check.
//   node scripts/make-smoke-built.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(join(repoRoot, 'tests', 'smoke.ts'), 'utf8')
const built = source
  .replaceAll("'../src/fs.ts'", "'../lib/fs.js'")
  .replaceAll("'../src/shell.ts'", "'../lib/shell.js'")
if (built === source) {
  console.error('make-smoke-built: no substitution applied — tests/smoke.ts no longer imports ../src/fs.ts or ../src/shell.ts; update this generator to match the rewrite in scripts/compatibility/Run-Checks.ps1')
  process.exit(1)
}
if (built.includes('../src/fs.ts') || built.includes('../src/shell.ts')) {
  console.error('make-smoke-built: leftover src/fs|shell imports after substitution')
  process.exit(1)
}
const out = `// GENERATED by scripts/make-smoke-built.mjs from tests/smoke.ts — do not edit or commit.\n` + built
writeFileSync(join(repoRoot, 'tests', 'smoke-built.ts'), out)
console.log('make-smoke-built: wrote tests/smoke-built.ts (fs/shell imports point at lib/)')
